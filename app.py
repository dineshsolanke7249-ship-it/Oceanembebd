import streamlit as st
import numpy as np
import json
import pandas as pd


with open("models/real_ocean_weights.json", "r") as f:
    weights = json.load(f)


def linear(x, weight, bias):
    return np.maximum(
        0,
        x @ np.array(weight).T + np.array(bias)
    )


def predict_temperature(
    latitude,
    longitude,
    sst,
    sss,
    depth
):
    x = np.array(
        [[latitude, longitude, sst, sss, depth]],
        dtype=np.float32
    )

    x = linear(
        x,
        weights["network.0.weight"],
        weights["network.0.bias"]
    )

    x = linear(
        x,
        weights["network.2.weight"],
        weights["network.2.bias"]
    )

    x = linear(
        x,
        weights["network.4.weight"],
        weights["network.4.bias"]
    )

    x = (
        x @ np.array(
            weights["network.6.weight"]
        ).T
        + np.array(
            weights["network.6.bias"]
        )
    )

    return float(x[0][0])


def get_ocean_region(latitude, longitude):

    if -90 <= latitude <= -60:
        return "Southern Ocean"

    if 66 <= latitude <= 90:
        return "Arctic Ocean"

    if 5 <= latitude <= 30 and 50 <= longitude <= 78:
        return "Arabian Sea"

    if 5 <= latitude <= 30 and 78 < longitude <= 100:
        return "Bay of Bengal"

    if -60 <= latitude < 5 and 20 <= longitude <= 147:
        return "Indian Ocean"

    if -60 <= latitude <= 66 and (
        longitude >= 120 or longitude <= -70
    ):
        return "Pacific Ocean"

    if -60 <= latitude <= 66 and -70 < longitude < 20:
        return "Atlantic Ocean"

    return "Open Ocean / Region not identified"


st.set_page_config(
    page_title="Ocean Deep Temperature Predictor",
    page_icon="🌊",
    layout="wide"
)


st.title("🌊 Ocean Deep Temperature Predictor")


st.write(
    "Predict ocean temperature at different "
    "depths using real satellite SST and "
    "surface salinity."
)


st.divider()


st.subheader("🌍 Ocean Location and Surface Data")


col1, col2 = st.columns(2)


with col1:

    latitude = st.number_input(
        "Latitude",
        min_value=-90.0,
        max_value=90.0,
        value=10.0
    )

    longitude = st.number_input(
        "Longitude",
        min_value=-180.0,
        max_value=180.0,
        value=70.0
    )


with col2:

    sst = st.number_input(
        "Surface Temperature / SST (°C)",
        value=28.5
    )

    sss = st.number_input(
        "Surface Salinity / SSS",
        value=35.2
    )


ocean_region = get_ocean_region(
    latitude,
    longitude
)


st.info(
    f"🌊 Detected Ocean / Sea Region: **{ocean_region}**"
)


st.caption(
    f"📍 Coordinates: {latitude:.2f}°, {longitude:.2f}°"
)


st.divider()


if st.button(
    "🔮 Predict Ocean Temperature",
    type="primary"
):

    results = []

    for depth in range(50, 1001, 50):

        temperature = predict_temperature(
            latitude,
            longitude,
            sst,
            sss,
            depth
        )

        results.append(
            (depth, temperature)
        )


    st.subheader("🌊 Predicted Ocean Temperature")


    st.caption(
        "Predictions are generated by the "
        "real-data trained model."
    )


    chart_data = pd.DataFrame(
        results,
        columns=[
            "Depth (m)",
            "Temperature (°C)"
        ]
    )


    st.line_chart(
        chart_data,
        x="Depth (m)",
        y="Temperature (°C)"
    )


    st.subheader("📊 Depth Profile")


    st.dataframe(
        chart_data,
        use_container_width=True,
        hide_index=True
    )